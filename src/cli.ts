// firebirdrest-js gen types: writes the TypeScript Database type of a
// FirebirdREST API, read from its OpenAPI document.

import { writeFileSync } from 'node:fs'
import { generateTypes, type OpenAPIDocument, type SchemaDocument } from './gen'

const usage = `Usage: firebirdrest-js gen types --url <FirebirdREST URL> [options]

Writes the TypeScript Database type for createClient<Database>() from the API's
OpenAPI document.

Options:
  --url <url>          the FirebirdREST API, e.g. http://localhost:3000 (or FIREBIRDREST_URL)
  --token <jwt>        a token whose role sees what should be typed (or FIREBIRDREST_TOKEN);
                       the document lists only what the role may use, unless the server
                       runs with openapi-mode = "ignore-privileges"
  --schema <a,b>       Firebird 6 schemas to include (default: every exposed schema)
  --output <file>      write to a file instead of standard output
  -h, --help           show this help`

function fail(msg: string): never {
  process.stderr.write(`firebirdrest-js: ${msg}\n`)
  process.exit(1)
}

async function fetchDoc(url: string, token: string | undefined, schema: string | undefined): Promise<OpenAPIDocument> {
  const headers: Record<string, string> = { Accept: 'application/openapi+json, application/json' }
  if (token) headers.Authorization = `Bearer ${token}`
  if (schema) headers['Accept-Profile'] = schema
  let res: Response
  try {
    res = await fetch(url.replace(/\/$/, '') + '/', { headers })
  } catch (e) {
    fail(`cannot reach ${url}: ${(e as Error).message}`)
  }
  const text = await res.text()
  if (!res.ok) fail(`${url} answered ${res.status}: ${text.slice(0, 300)}`)
  try {
    return JSON.parse(text)
  } catch {
    fail(`${url} did not return an OpenAPI document`)
  }
}

async function main(argv: string[]) {
  const opts: Record<string, string> = {}
  const pos: string[] = []
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '-h' || a === '--help') {
      process.stdout.write(usage + '\n')
      return
    }
    if (a.startsWith('--')) {
      const [k, v] = a.includes('=') ? [a.slice(2, a.indexOf('=')), a.slice(a.indexOf('=') + 1)] : [a.slice(2), argv[++i]]
      if (v === undefined) fail(`${a} needs a value`)
      opts[k] = v
    } else pos.push(a)
  }
  if (pos[0] !== 'gen' || pos[1] !== 'types') fail(`unknown command "${pos.join(' ')}"\n\n${usage}`)
  for (const k of Object.keys(opts)) if (!['url', 'token', 'schema', 'output'].includes(k)) fail(`unknown option --${k}`)
  const url = opts.url ?? process.env.FIREBIRDREST_URL
  if (!url) fail(`--url is required\n\n${usage}`)
  const token = opts.token ?? process.env.FIREBIRDREST_TOKEN

  const first = await fetchDoc(url, token, undefined)
  const ext = first.info?.['x-firebirdrest']
  const exposed = ext?.schemas ?? []
  const wanted = opts.schema ? opts.schema.split(',').map((s) => s.trim()).filter(Boolean) : exposed
  const docs: SchemaDocument[] = []
  if (wanted.length === 0) {
    // Firebird 3-5, or a server before 0.7: one namespace, typed as "public"
    docs.push({ name: ext?.schema || 'public', doc: first })
  } else {
    for (const s of wanted) {
      if (exposed.length && !exposed.includes(s)) fail(`schema "${s}" is not exposed; exposed: ${exposed.join(', ')}`)
      docs.push({ name: s, doc: s === ext?.schema ? first : await fetchDoc(url, token, s) })
    }
  }
  const header = [
    'Generated by firebirdrest-js gen types. Do not edit: regenerate after schema changes.',
    `FirebirdREST ${first.info?.version ?? '?'}${ext?.firebird ? `, Firebird ${ext.firebird}` : ''}`,
  ].join('\n')
  const { source, notes } = generateTypes(docs, header)
  for (const n of notes) process.stderr.write(`note: ${n}\n`)
  if (opts.output) {
    writeFileSync(opts.output, source)
    process.stderr.write(`wrote ${opts.output}: ${docs.map((d) => d.name).join(', ')}\n`)
  } else process.stdout.write(source)
}

main(process.argv.slice(2)).catch((e) => fail(e instanceof Error ? e.message : String(e)))
